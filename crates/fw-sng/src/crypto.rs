//! SNG encryption: AES-256-CTR with a 128-bit big-endian counter.

use aes::Aes256;
use ctr::Ctr128BE;
use ctr::cipher::{KeyIvInit, StreamCipher};

use crate::Platform;

const KEY_PC: [u8; 32] = [
    0xCB, 0x64, 0x8D, 0xF3, 0xD1, 0x2A, 0x16, 0xBF, 0x71, 0x70, 0x14, 0x14, 0xE6, 0x96, 0x19, 0xEC,
    0x17, 0x1C, 0xCA, 0x5D, 0x2A, 0x14, 0x2E, 0x3E, 0x59, 0xDE, 0x7A, 0xDD, 0xA1, 0x8A, 0x3A, 0x30,
];
const KEY_MAC: [u8; 32] = [
    0x98, 0x21, 0x33, 0x0E, 0x34, 0xB9, 0x1F, 0x70, 0xD0, 0xA4, 0x8C, 0xBD, 0x62, 0x59, 0x93, 0x12,
    0x69, 0x70, 0xCE, 0xA0, 0x91, 0x92, 0xC0, 0xE6, 0xCD, 0xA6, 0x76, 0xCC, 0x98, 0x38, 0x28, 0x9D,
];

/// Encrypts or decrypts in place (CTR is symmetric).
pub(crate) fn apply(data: &mut [u8], platform: Platform, iv: &[u8; 16]) {
    let key = match platform {
        Platform::Pc => &KEY_PC,
        Platform::Mac => &KEY_MAC,
    };
    Ctr128BE::<Aes256>::new(key.into(), iv.into()).apply_keystream(data);
}
